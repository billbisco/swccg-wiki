def patch_list() -> bool:
    text = LIST.read_text(encoding="utf-8")
    row = (
        "| 2012-02-10 || [[2012 Match Play Championship|Match Play Championship]] "
        "|| 10–12 February 2012 || — || [[Legacy Open]] || —\n"
    )
    if "2012 Match Play Championship" in text:
        return False
    if "== 2012 ==" in text:
        close = text.find("|}", text.find("== 2012 =="))
        if close == -1:
            raise SystemExit("List of tournaments 2012 table missing close")
        LIST.write_text(
            text[:close] + "|-\n" + row + text[close:],
            encoding="utf-8",
            newline="\n",
        )
        return True
    section = (
        "\n== 2012 ==\n\n"
        '{| class="wikitable sortable"\n'
        "|-\n"
        "! Tag !! Event !! Dates !! Site !! Format !! Winner\n"
        "|-\n"
        f"{row}"
        "|}\n\n"
    )
    for needle in ("== 2011 ==", "== 2010 ==", "== 2009 ==", "== 2008 ==", "== 2007 =="):
        if needle in text:
            LIST.write_text(
                text.replace(needle, section + needle, 1),
                encoding="utf-8",
                newline="\n",
            )
            return True
    m = re.search(r"(== 2013 ==.*?)\|}\n", text, re.S)
    if not m:
        raise SystemExit("List of tournaments missing 2013 section")
    text = text[: m.end()] + section + text[m.end() :]
    LIST.write_text(text, encoding="utf-8", newline="\n")
    return True


